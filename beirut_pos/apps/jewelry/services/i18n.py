def get_ui_language() -> str:
    value = str(get_config_value("ui_language", "ar") or "ar").lower()
    if value not in _SUPPORTED_LANGUAGES:
        return "ar"
    return value


def set_ui_language(language: str) -> None:
    normalized = str(language).lower()
    if normalized not in _SUPPORTED_LANGUAGES:
        normalized = "ar"
    set_config_value("ui_language", normalized)


def t(key: str, *, language: str | None = None, **kwargs) -> str:
    lang = language or get_ui_language()
    translations = _TEXTS.get(key)
    if not translations:
        return key
    value = translations.get(lang) or translations.get("en") or key
    if not kwargs:
        return value
    try:
        return value.format(**kwargs)
    except Exception:
        return value


def choose_name(name_ar: str, name_en: str, *, language: str | None = None) -> str:
    lang = language or get_ui_language()
    if lang == "ar":
        return name_ar or name_en
    return name_en or name_ar
